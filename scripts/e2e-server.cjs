const { _electron: electron } = require('playwright');
const path = require('path');
const fs = require('fs');
const [out, profile] = process.argv.slice(2);
const check = (label, ok, detail = '') => { console.log(`${ok ? 'PASS' : 'FAIL'}  ${label}${detail ? '  — ' + detail : ''}`); if (!ok) process.exitCode = 1; };
(async () => {
  const app = await electron.launch({ executablePath: require('electron'), args: [path.resolve(__dirname, '..'), '--no-sandbox', `--user-data-dir=${profile}`] });
  const win = await app.firstWindow();
  const errors = [];
  win.on('pageerror', (e) => errors.push(e.message));
  await win.waitForTimeout(2000);
  const bad = await win.evaluate(() => window.obsidian.connectServer({ url: '127.0.0.1:4533', username: 'alby', password: 'nope' }).then(() => 'connected?!', (e) => e.message));
  check('wrong password → clear error', /Wrong username or password/.test(bad), bad);
  const unreachable = await win.evaluate(() => window.obsidian.connectServer({ url: 'http://127.0.0.1:4999', username: 'a', password: 'b' }).then(() => 'connected?!', (e) => e.message));
  check('unreachable server → clear error', /Couldn’t reach the server/.test(unreachable), unreachable);
  const status = await win.evaluate(() => window.obsidian.connectServer({ url: '127.0.0.1:4533/app', username: 'alby', password: 'test-pass-123' }));
  check('connects (address without http://, web UI path stripped)', status.configured && /Navidrome 0\.58/.test(status.serverName ?? ''), JSON.stringify(status));
  const stored = fs.readFileSync(path.join(profile, 'server.json'), 'utf8');
  check('password not stored', !stored.includes('test-pass-123'), stored.slice(0, 160));
  const albums = await win.evaluate(() => window.obsidian.serverAlbums());
  check('server albums', albums.length === 1 && !!albums[0].thumbnail, JSON.stringify(albums[0]).slice(0, 200));
  const album = await win.evaluate((id) => window.obsidian.serverAlbum(id), albums[0].id);
  const viva = album.tracks.find((t) => t.title === 'Viva la Vida');
  check('server album tracks with hi-res format', album.tracks.length === 2 && viva?.format?.lossless && viva.format.bitDepth === 24 && viva.format.sampleRate === 48000, JSON.stringify(viva).slice(0, 300));
  const probe = await win.evaluate(async ({ id, art }) => {
    const r = await fetch(`media://server/${id}`, { headers: { Range: 'bytes=0-15' } });
    const b = new Uint8Array(await r.arrayBuffer());
    const a = await fetch(art);
    return { status: r.status, magic: String.fromCharCode(...b.slice(0, 4)), range: r.headers.get('content-range'), art: a.headers.get('content-type') };
  }, { id: viva.videoId.replace(/^srv_/, ''), art: album.thumbnail });
  check('media://server streams the original FLAC (byte ranges)', probe.status === 206 && probe.magic === 'fLaC', JSON.stringify(probe));
  check('server cover art', /image/.test(probe.art ?? ''), probe.art);
  const match = await win.evaluate(async () => {
    const r = await fetch('ytstream://track/ZZZZZZZZZZ9?q=lossless&t=' + encodeURIComponent('Viva La Vida') + '&a=Coldplay&d=242', { headers: { Range: 'bytes=0-3' } });
    return { status: r.status, magic: String.fromCharCode(...new Uint8Array(await r.arrayBuffer())), info: await window.obsidian.streamInfo('ZZZZZZZZZZ9') };
  });
  check('lossless match from the SERVER for a YouTube song', match.magic === 'fLaC' && match.info?.source === 'server', JSON.stringify(match));
  const yours = await win.evaluate(() => window.obsidian.searchYourMusic('coldplay'));
  check('Your Music search covers folders + server', yours.some((t) => t.source === 'local') && yours.some((t) => t.source === 'server'), yours.map((t) => `${t.title}(${t.source})`).join(', '));

  // UI: the Server tab, and play a server song.
  await win.getByRole('button', { name: 'Your Music' }).click();
  await win.getByRole('tab', { name: 'Server', exact: true }).click();
  await win.waitForTimeout(1200);
  await win.screenshot({ path: `${out}/30-server-albums.png` });
  await win.locator('main button.truncate').first().click();
  await win.waitForTimeout(1200);
  await win.locator('[role=listitem]', { hasText: 'Viva la Vida' }).hover();
  await win.click('button[aria-label="Play Viva la Vida"]');
  await win.waitForTimeout(3000);
  const bar = await win.evaluate(() => document.querySelector('[aria-label=Player]')?.textContent);
  check('server song plays with HI-RES badge', /Viva la Vida/.test(bar) && /HI-RES/.test(bar), bar);
  await win.screenshot({ path: `${out}/31-server-album-playing.png` });

  // Customisation: accent Apple Blue, graphite, compact, glow; then the settings tabs.
  await win.getByRole('button', { name: 'Settings' }).click();
  await win.locator('main').getByRole('tab', { name: 'Your Music', exact: true }).click();
  await win.waitForTimeout(800);
  await win.screenshot({ path: `${out}/32-settings-music.png` });
  await win.locator('main').getByRole('tab', { name: 'Appearance' }).click();
  await win.click('button[aria-label="Apple Blue"]');
  await win.locator('main').getByRole('radio', { name: 'Graphite' }).click();
  await win.click('button[aria-label="Ambient glow"]');
  await win.waitForTimeout(1200);
  await win.screenshot({ path: `${out}/33-settings-appearance.png` });
  await win.locator('main').getByRole('tab', { name: 'Lyrics', exact: true }).click();
  await win.locator('main').getByRole('radio', { name: 'Centre' }).click();
  await win.locator('main').getByRole('radio', { name: 'L', exact: true }).click();
  await win.locator('main').getByRole('radio', { name: 'Rounded' }).click();
  await win.waitForTimeout(600);
  await win.screenshot({ path: `${out}/34-settings-lyrics.png` });
  await win.locator('main').getByRole('tab', { name: 'Player', exact: true }).click();
  await win.locator('main').getByRole('radio', { name: 'Blurred artwork' }).click();
  await win.locator('main').getByRole('tab', { name: 'Layout', exact: true }).click();
  await win.click('button[aria-label="Compact song lists"]');
  await win.waitForTimeout(500);
  await win.screenshot({ path: `${out}/35-settings-layout.png` });
  await win.getByRole('button', { name: 'Your Music' }).first().click();
  await win.getByRole('tab', { name: 'Songs', exact: true }).click();
  await win.waitForTimeout(800);
  await win.screenshot({ path: `${out}/36-compact-ocean.png` });
  await win.click('button[aria-label="Open the full-screen player"]');
  await win.waitForTimeout(2500);
  await win.screenshot({ path: `${out}/37-fullscreen-artwork-backdrop.png` });
  const settings = JSON.parse(fs.readFileSync(path.join(profile, 'library.json'), 'utf8')).settings;
  check('settings persisted', settings.accent === '#0a84ff' && settings.pageTone === 'graphite' && settings.compact && settings.backdrop === 'artwork' && settings.lyricsAlign === 'center', JSON.stringify({ accent: settings.accent, tone: settings.pageTone, compact: settings.compact, backdrop: settings.backdrop, align: settings.lyricsAlign }));
  console.log('page errors:', errors.join(' | ') || 'none');
  await app.close();
})().catch((e) => { console.error('E2E FAILED', e); process.exit(1); });
